#!/usr/bin/env node
// Generates public/config.public.js — the ONLY key file that gets deployed.
//
// It copies an explicit allow-list of keys out of public/config.local.js (your
// machine-only file, which may also hold the paid Google Maps key). Anything
// not on the list — e.g. googleMapsKey — can never reach the public site;
// visitors who want Google Photorealistic paste their own key into the panel.
//
// Runs automatically as the Firebase Hosting `predeploy` hook. In CI there is
// no config.local.js; the workflow writes config.public.js itself and this
// script just leaves it alone.

const fs = require('fs');
const path = require('path');

const PUBLIC_KEYS = ['cesiumIonToken'];   // <- the allow-list. Keep it short.

const pub = path.join(__dirname, '..', 'public');
const localFile = path.join(pub, 'config.local.js');
const publicFile = path.join(pub, 'config.public.js');

function readConfig(file) {
  // Evaluate the file in a sandbox that only exposes `window`.
  const src = fs.readFileSync(file, 'utf8');
  const sandbox = { window: {} };
  new Function('window', src)(sandbox.window);
  return sandbox.window.CONFIG || {};
}

if (!fs.existsSync(localFile)) {
  if (fs.existsSync(publicFile)) {
    console.log('[build-public-config] no config.local.js; keeping existing config.public.js');
    process.exit(0);
  }
  console.error('[build-public-config] neither public/config.local.js nor public/config.public.js exists — nothing to deploy a Cesium token from.');
  process.exit(1);
}

const local = readConfig(localFile);
const out = {};
for (const k of PUBLIC_KEYS) if (local[k]) out[k] = String(local[k]);

if (!out.cesiumIonToken) {
  console.error('[build-public-config] config.local.js has no cesiumIonToken — the deployed site would have no 3D buildings. Aborting.');
  process.exit(1);
}

const dropped = Object.keys(local).filter((k) => !PUBLIC_KEYS.includes(k) && local[k]);
const banner =
  '// GENERATED by scripts/build-public-config.js — do not edit, do not commit.\n' +
  '// Contains only keys that are safe to publish. Visitors add their own Google key in the panel.\n';
fs.writeFileSync(publicFile, banner + 'window.CONFIG = Object.assign(window.CONFIG || {}, ' + JSON.stringify(out, null, 2) + ');\n');

console.log(`[build-public-config] wrote public/config.public.js with: ${Object.keys(out).join(', ')}` +
  (dropped.length ? `  (kept private: ${dropped.join(', ')})` : ''));
